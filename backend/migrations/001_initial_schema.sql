-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==========================================
-- 1. TECHNICIANS (Técnicos de Campo)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.technicians (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT DEFAULT 'Pendente (Cadastrar via Telegram)',
    telegram_id TEXT UNIQUE,
    email TEXT DEFAULT 'Pendente',
    role TEXT NOT NULL DEFAULT 'Técnico de Campo',
    avatar_url TEXT DEFAULT 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?auto=format&fit=crop&w=250&q=80',
    status TEXT NOT NULL DEFAULT 'Ativo',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 2. APPOINTMENTS (Agenda de Atendimentos)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id TEXT UNIQUE,
    title TEXT NOT NULL,
    client_name TEXT,
    client_address TEXT,
    client_contact TEXT DEFAULT 'Sincronizado da Agenda Online',
    appointment_date DATE,
    appointment_time TEXT DEFAULT '08:00',
    status TEXT NOT NULL DEFAULT 'Agendado',
    technician_names TEXT DEFAULT 'Equipe de Campo',
    technician_id BIGINT REFERENCES public.technicians(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 3. APPOINTMENT_TECHNICIANS (Junction N:N Atendimentos <-> Técnicos)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.appointment_technicians (
    appointment_id BIGINT NOT NULL REFERENCES public.appointments(id) ON DELETE CASCADE,
    technician_id BIGINT NOT NULL REFERENCES public.technicians(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (appointment_id, technician_id)
);

-- ==========================================
-- 4. EQUIPMENT_CATEGORIES (Categorias de Equipamentos Médicos)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.equipment_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 5. TEST_TEMPLATES (Templates de Testes / Checklists)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.test_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES public.equipment_categories(id) ON DELETE CASCADE,
    name TEXT NOT NULL DEFAULT '',
    analyzer_type TEXT NOT NULL DEFAULT '',
    description TEXT,
    required_parameters JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_mandatory INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 6. ANALYZERS (Analisadores e Padrões de Teste)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.analyzers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    category_id BIGINT REFERENCES public.equipment_categories(id) ON DELETE SET NULL,
    type TEXT,
    serial_number TEXT,
    brand_model TEXT,
    calibration_date DATE,
    calibration_expiry DATE,
    calibration_due DATE,
    status TEXT NOT NULL DEFAULT 'Disponível',
    current_location TEXT DEFAULT 'Almoxarifado Central',
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 7. RESERVATIONS (Reservas e Checkout/Checkin de Analisadores)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analyzer_id BIGINT REFERENCES public.analyzers(id) ON DELETE CASCADE,
    technician_id BIGINT REFERENCES public.technicians(id) ON DELETE CASCADE,
    appointment_id BIGINT REFERENCES public.appointments(id) ON DELETE CASCADE,
    reserved_date DATE,
    checkout_date TIMESTAMPTZ,
    checkout_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    checkin_date TIMESTAMPTZ,
    checkin_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'Reservado',
    notes TEXT DEFAULT 'Reserva efetuada via sistema/Telegram',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 8. APPOINTMENT_EQUIPMENTS (Equipamentos de Hospital Atendidos)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.appointment_equipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES public.appointments(id) ON DELETE CASCADE,
    category_id BIGINT REFERENCES public.equipment_categories(id) ON DELETE SET NULL,
    model TEXT,
    serial_number TEXT,
    tag TEXT,
    sector TEXT DEFAULT 'Engenharia Clínica',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ==========================================
-- 9. NOTIFICATION_LOGS (Logs de Notificações Telegram/Cron)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT REFERENCES public.appointments(id) ON DELETE SET NULL,
    technician_id BIGINT REFERENCES public.technicians(id) ON DELETE CASCADE,
    type TEXT,
    message TEXT,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    status TEXT
);

