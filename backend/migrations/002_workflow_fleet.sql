-- A migração é aditiva e não altera o contrato/gerador do relatório PDF.

ALTER TABLE public.appointments
  ADD COLUMN IF NOT EXISTS workflow_status TEXT NOT NULL DEFAULT 'Data provisória',
  ADD COLUMN IF NOT EXISTS workflow_validated_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS commercial_confirmed_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS last_activity_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  ADD COLUMN IF NOT EXISTS vehicle_id BIGINT,
  ADD COLUMN IF NOT EXISTS vehicle_assigned_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS public.fleet_vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  plate TEXT NOT NULL UNIQUE,
  brand_model TEXT,
  status TEXT NOT NULL DEFAULT 'Disponível',
  current_km NUMERIC(12, 1) NOT NULL DEFAULT 0,
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.appointments'::regclass AND conname = 'appointments_vehicle_id_fkey') THEN
    ALTER TABLE public.appointments ADD CONSTRAINT appointments_vehicle_id_fkey
      FOREIGN KEY (vehicle_id) REFERENCES public.fleet_vehicles(id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.fleet_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id BIGINT NOT NULL REFERENCES public.fleet_vehicles(id) ON DELETE RESTRICT,
  appointment_id BIGINT REFERENCES public.appointments(id) ON DELETE SET NULL,
  withdrawn_by_user_id TEXT,
  withdrawn_by_name TEXT,
  returned_by_user_id TEXT,
  returned_by_name TEXT,
  status TEXT NOT NULL DEFAULT 'Em Uso',
  checkout_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  checkin_at TIMESTAMPTZ,
  km_initial NUMERIC(12, 1) NOT NULL,
  km_final NUMERIC(12, 1),
  odometer_photo_url TEXT,
  odometer_photo_data TEXT,
  return_photo_url TEXT,
  return_photo_data TEXT,
  checkout_inspection JSONB NOT NULL DEFAULT '{}'::jsonb,
  return_inspection JSONB NOT NULL DEFAULT '{}'::jsonb,
  fuel_checked BOOLEAN,
  tires_calibrated BOOLEAN,
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_fleet_vehicles_status ON public.fleet_vehicles(status);
CREATE INDEX IF NOT EXISTS idx_fleet_usage_vehicle_status ON public.fleet_usage(vehicle_id, status);
CREATE INDEX IF NOT EXISTS idx_fleet_usage_appointment ON public.fleet_usage(appointment_id);
CREATE INDEX IF NOT EXISTS idx_appointments_vehicle_date ON public.appointments(vehicle_id, appointment_date);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fleet_usage_active_vehicle
  ON public.fleet_usage(vehicle_id) WHERE status = 'Em Uso';

ALTER TABLE public.fleet_vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fleet_usage ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated fleet vehicles" ON public.fleet_vehicles;
DROP POLICY IF EXISTS "Authenticated fleet usage" ON public.fleet_usage;
-- ATEM authenticates through Express JWT, not Supabase Auth. Only the backend
-- service role may access operational records and private photos directly.
REVOKE ALL ON public.fleet_vehicles, public.fleet_usage FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.fleet_vehicles, public.fleet_usage TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.fleet_vehicles_id_seq, public.fleet_usage_id_seq TO service_role;
